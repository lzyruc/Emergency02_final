# ==================== 置信度: 两条证据 + 软与 ====================
# 【为什么要重写这一段 —— 之前 2 个误检的根因】
# 老公式是 s_color = max(绝对蓝 c_p75, 绝对蓝 c_med, 色度 c_rel), 一个 max
# 就让"绝对蓝"可以**盖过**色度的否决. 绝对差 B-R 会随光照和距离整体缩放:
# 同一个灰蓝垃圾桶, 站 1.8m 拍 col=0.289(判负), 走到 1.0m 拍 col=0.98(判正),
# 而它的色度 rel 两次几乎没变(0.485 / 0.60). 一个"值本身取决于距离和光照"的
# 特征, 不能当主证据. (这正是你说的"垃圾桶是灰蓝色, rgb 中不一样".)
# 所以: 绝对蓝 B-R 只保留在 blue_mask 的分割阈值里(负责"哪些像素算蓝"),
# 彻底退出置信度打分; 打分只用**色度**和**尺寸**两条, 而且用软与(必须都成立).

